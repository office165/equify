"""Round 11: the wizard's and the results page's CSS have some colours written as values instead of tokens (dark panels, light text).
For the day theme of SITE_V2, list every rule that sets one of them and write a rule that puts the token in its place.
    python3 scripts/round-11/wizard_light_overrides.py components/wizard/equify/wizard-equify.css > public/site-v2/wizard-light.css
    python3 scripts/round-11/wizard_light_overrides.py components/results/results-report.css components/results/equify-scroll-report.css > public/site-v2/results-light.css
"""
import re, sys
files = sys.argv[1:] or ['components/wizard/equify/wizard-equify.css']
src = '\n'.join(open(f).read() for f in files)
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
DARK_BG = re.compile(r'rgba\(\s*(2|5|6|9|11|15)\s*,\s*(5|15|20|28|32|46)\s*,\s*(4|13|18|24|28|41)\s*,|#111815|#0b201c|#091c18|#050f0d|#0f2e29|#163530|#020504', re.I)
LIGHT_TX = re.compile(r'#(cbd5e1|f5f7f6|94a3b8|fff|ffffff|e8f2f0|e2e8f0)\b|rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*0?\.(9|8|7)', re.I)
DIM_TX = re.compile(r'#(94a3b8|7fa8a2|475569|64748b)\b', re.I)
out = []
def walk(css, wrap=None):
    i = 0
    while i < len(css):
        j = css.find('{', i)
        if j < 0: break
        sel = css[i:j].strip()
        if sel.startswith('@media') or sel.startswith('@supports'):
            depth, k = 1, j + 1
            while depth and k < len(css):
                depth += {'{': 1, '}': -1}.get(css[k], 0); k += 1
            walk(css[j + 1:k - 1], sel); i = k; continue
        k = css.find('}', j)
        body = css[j + 1:k]; i = k + 1
        if sel.startswith('@') or not sel: continue
        decl = []
        for d in body.split(';'):
            if ':' not in d: continue
            p, v = d.split(':', 1); p = p.strip().lower(); v = v.strip()
            if p in ('background', 'background-color', 'background-image') and DARK_BG.search(v):
                decl.append('background: var(--bg-surface) !important')
            elif p == 'color' and DIM_TX.search(v):
                decl.append('color: var(--bone-dim) !important')
            elif p == 'color' and LIGHT_TX.search(v):
                decl.append('color: var(--bone) !important')
            elif p in ('border-color', 'border', 'border-bottom', 'border-top') and DARK_BG.search(v):
                decl.append(f'{p}: ' + DARK_BG.sub('rgba(8, 32, 28, .12)', v) + ' !important') if 'rgba' in v else None
        if decl:
            sels = ', '.join('html.eq-v2[data-eq-theme="light"] ' + s.strip() for s in sel.split(','))
            rule = f'{sels} {{ {"; ".join(dict.fromkeys(decl))} }}'
            out.append(f'{wrap} {{ {rule} }}' if wrap else rule)
walk(src)
print(f"/* Round 11 (SITE_V2), day theme: generated by scripts/round-11/wizard_light_overrides.py from {', '.join(files)}. */")
print('\n'.join(out))
